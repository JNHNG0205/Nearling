// Generates the device's Closet costume layers from the same code the web draws them with
// (packages/sprites/src/costumes.ts), in the same clip order as art/nearling_sprites.h.
// Also writes the device copy of art/nearling_sprites.h with its frame bytes in nearling_frames_data.S.
// Run from the repo root:  packages/sprites/node_modules/.bin/tsx firmware/tools/export-costumes.ts
// Output: firmware/petto/nearling_costumes.h, nearling_costumes.cpp (small tables) and
// nearling_costumes_data.S (the two big tables as assembler data: compiles in seconds, where the
// same arrays in C++ took about 30 minutes). Do not edit by hand.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { COSTUME_KEYS, COSTUME_RGB, clip, pack4 } from "../../packages/sprites/src/index";
import { exportClips } from "../../packages/sprites/scripts/export";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../petto");
const NONE = 0xffff;
const rgb565 = ([r, g, b]: readonly number[]) => ((r! & 0xf8) << 8) | ((g! & 0xfc) << 3) | (b! >> 3);
const hex = (v: number, w: number) => `0x${v.toString(16).padStart(w, "0")}`;

const clips = exportClips();
// frame offset of each clip into the per-costume reference table; eggs wear nothing
const ofs: number[] = [];
let frameRefs = 0;
for (const c of clips) {
  if (c.stage === "egg") { ofs.push(NONE); continue; }
  ofs.push(frameRefs);
  frameRefs += c.clip.frames.length;
}

// layer pool: identical 4 bpp layers stored once; all-clear layers are NONE
const pool: Uint8Array[] = [];
const poolIndex = new Map<string, number>();
const add = (b: number[] | Uint8Array): number => {
  if (!b.some((v) => v)) return NONE;
  const packed = pack4(b as never);
  const key = packed.join(",");
  let i = poolIndex.get(key);
  if (i === undefined) { i = pool.length; pool.push(packed); poolIndex.set(key, i); }
  return i;
};
const refs: number[] = [];
for (const key of COSTUME_KEYS) {
  for (const c of clips) {
    if (c.stage === "egg") continue;
    const k = clip(c.anim, { stage: c.stage, winged: c.winged, personality: c.personality, costume: key });
    if (!k.costume || k.costume.length !== c.clip.frames.length) throw new Error(`costume ${key}: frame mismatch in ${c.anim}`);
    for (const layer of k.costume) refs.push(add(layer.back), add(layer.front));
  }
}

const h = `// GENERATED by firmware/tools/export-costumes.ts from packages/sprites/src/costumes.ts. Do not edit.
// Closet costumes: per frame of every NL_CLIPS clip, a back layer (drawn behind the pet) and a front
// layer (drawn over everything), 4 bpp like NL_FRAME_DATA, colours from NL_COSTUME_PALETTE.
#pragma once
#include <stdint.h>

#define NL_COSTUME_COUNT ${COSTUME_KEYS.length}
#define NL_COSTUME_NONE 0xffff
#define NL_COSTUME_CLIPS ${clips.length}
#define NL_COSTUME_FRAME_REFS ${frameRefs}
#define NL_COSTUME_LAYER_COUNT ${pool.length}
extern const char* const NL_COSTUME_KEYS[NL_COSTUME_COUNT];
extern const uint16_t NL_COSTUME_PALETTE[16];
// Per NL_CLIPS index: offset into a costume's frame refs, NL_COSTUME_NONE for eggs.
extern const uint16_t NL_COSTUME_CLIP_OFS[NL_COSTUME_CLIPS];
// Per NL_CLIPS index: frame count when this file was made (check against NL_CLIPS at boot).
extern const uint8_t NL_COSTUME_CLIP_FRAMES[NL_COSTUME_CLIPS];
// [costume][frame ref][back, front] layer ids.
extern const uint16_t NL_COSTUME_REF[NL_COSTUME_COUNT * NL_COSTUME_FRAME_REFS * 2];
extern const uint32_t NL_COSTUME_LAYERS[NL_COSTUME_LAYER_COUNT * 128];

static inline const uint8_t* nl_costume_layer(uint16_t id) { return (const uint8_t*)NL_COSTUME_LAYERS + (uint32_t)id * 512; }
`;

const words: string[] = [];
for (const p of pool)
  for (let i = 0; i < p.length; i += 4)   // little endian, so the bytes stay in pack4 order in memory
    words.push(hex((p[i]! | (p[i + 1]! << 8) | (p[i + 2]! << 16) | (p[i + 3]! << 24)) >>> 0, 8));
const rows = (xs: string[], per: number) => {
  const out: string[] = [];
  for (let i = 0; i < xs.length; i += per) out.push("  " + xs.slice(i, i + per).join(","));
  return out.join(",\n");
};
const cpp = `// GENERATED by firmware/tools/export-costumes.ts. Do not edit.
#include "nearling_costumes.h"

const char* const NL_COSTUME_KEYS[NL_COSTUME_COUNT] = { ${COSTUME_KEYS.map((k) => `"${k}"`).join(", ")} };
const uint16_t NL_COSTUME_PALETTE[16] = { ${COSTUME_RGB.map((c) => hex(rgb565(c), 4)).join(", ")} };
const uint16_t NL_COSTUME_CLIP_OFS[NL_COSTUME_CLIPS] = { ${ofs.map((v) => (v === NONE ? "0xffff" : String(v))).join(", ")} };
const uint8_t NL_COSTUME_CLIP_FRAMES[NL_COSTUME_CLIPS] = { ${clips.map((c) => c.clip.frames.length).join(", ")} };
// NL_COSTUME_REF and NL_COSTUME_LAYERS live in nearling_costumes_data.S
`;
// Global C++ variables are not name-mangled, so the assembler symbols link to the extern declarations.
const asmRows = (dir: string, xs: string[], per: number) => {
  const out: string[] = [];
  for (let i = 0; i < xs.length; i += per) out.push(`  ${dir} ${xs.slice(i, i + per).join(",")}`);
  return out.join("\n");
};
const asm = `/* GENERATED by firmware/tools/export-costumes.ts. Do not edit. */
  .section .rodata.nl_costume_ref,"a"
  .global NL_COSTUME_REF
  .align 4
NL_COSTUME_REF:
${asmRows(".short", refs.map((v) => hex(v, 4)), 32)}
  .size NL_COSTUME_REF, ${refs.length * 2}

  .section .rodata.nl_costume_layers,"a"
  .global NL_COSTUME_LAYERS
  .align 4
NL_COSTUME_LAYERS:
${asmRows(".word", words, 16)}
  .size NL_COSTUME_LAYERS, ${words.length * 4}
`;
// The sprite header's frame table, same treatment: art/nearling_sprites.h keeps everything but the
// NL_FRAME_DATA bytes, which move to nearling_frames_data.S (the .ino recompiles on every upload).
const spritesSrc = readFileSync(join(OUT, "../../art/nearling_sprites.h"), "utf8").replace(/\r\n/g, "\n");
const START = "static const uint8_t NL_FRAME_DATA[NL_FRAME_COUNT * NL_FRAME_BYTES] = {\n";
const a = spritesSrc.indexOf(START);
const b = spritesSrc.indexOf("\n};\n", a);
if (a < 0 || b < 0) throw new Error("NL_FRAME_DATA not found in art/nearling_sprites.h");
const bytes = spritesSrc.slice(a + START.length, b).match(/0x[0-9a-fA-F]{2}/g) ?? [];
const frameCount = Number(/#define NL_FRAME_COUNT (\d+)/.exec(spritesSrc)?.[1]);
if (bytes.length !== frameCount * 512) throw new Error(`NL_FRAME_DATA has ${bytes.length} bytes, expected ${frameCount * 512}`);
writeFileSync(
  join(OUT, "nearling_sprites.h"),
  spritesSrc.slice(0, a) +
    "// Device copy (firmware/tools/export-costumes.ts): the bytes are in nearling_frames_data.S.\n" +
    "extern const uint8_t NL_FRAME_DATA[NL_FRAME_COUNT * NL_FRAME_BYTES];" +
    spritesSrc.slice(b + 3),
);
writeFileSync(
  join(OUT, "nearling_frames_data.S"),
  `/* GENERATED by firmware/tools/export-costumes.ts from art/nearling_sprites.h. Do not edit. */
  .section .rodata.nl_frame_data,"a"
  .global NL_FRAME_DATA
  .align 4
NL_FRAME_DATA:
${asmRows(".byte", bytes, 32)}
  .size NL_FRAME_DATA, ${bytes.length}
`,
);

writeFileSync(join(OUT, "nearling_costumes.h"), h);
writeFileSync(join(OUT, "nearling_costumes.cpp"), cpp);
writeFileSync(join(OUT, "nearling_costumes_data.S"), asm);
console.log(`${COSTUME_KEYS.length} costumes, ${clips.length} clips, ${frameRefs} frame refs, ${pool.length} layers = ${((pool.length * 512) / 1024).toFixed(0)} KB`);
