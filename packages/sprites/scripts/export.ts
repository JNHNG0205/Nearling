// Generates the firmware and art files from the same frames the web renders.
//   art/nearling_sprites.h   C header for the ESP32 (4 bpp frames in flash, RGB565 palettes, clip table)
//   art/sprites.json         clip metadata (names, fps, loop, frame counts) for any other tool
//   art/sheets/*.png         review sheets
// Usage: pnpm --filter @nearling/sprites export
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { BODY_PALETTES, EGG_ANIMS, PET_ANIMS, SIZE, clip, pack4, paletteFor, toRgba, type AnyAnim, type Stage } from "../src/index";
import { buildPalette, type Rgb } from "../src/palette";
import { encodePng } from "./png";

const ART = join(dirname(fileURLToPath(import.meta.url)), "../../../art");
mkdirSync(join(ART, "sheets"), { recursive: true });

const rgb565 = ([r, g, b]: Rgb) => ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3);
const hex16 = (v: number) => `0x${v.toString(16).padStart(4, "0")}`;
const ident = (s: string) => s.toUpperCase().replace(/[^A-Z0-9]/g, "_");

type Set = { stage: Stage; winged: boolean; anims: AnyAnim[] };
const SETS: Set[] = [
  { stage: "egg", winged: false, anims: Object.keys(EGG_ANIMS) as AnyAnim[] },
  ...(["baby", "teen", "adult"] as const).flatMap((stage) =>
    [false, true].map((winged) => ({ stage, winged, anims: Object.keys(PET_ANIMS) as AnyAnim[] })),
  ),
];

const lines: string[] = [];
const table: string[] = [];
const meta: Record<string, unknown>[] = [];
let totalFrames = 0;

lines.push(
  "// GENERATED by packages/sprites/scripts/export.ts. Do not edit; change the poses and re-run.",
  "// Spec: web-app architectual/07-pet-animation.md",
  "#pragma once",
  "#include <stdint.h>",
  "",
  `#define NL_SPRITE_SIZE ${SIZE}`,
  `#define NL_FRAME_BYTES ${(SIZE * SIZE) / 2}  // 4 bits per pixel, high nibble = left pixel, index 0 = transparent`,
  "",
  "// Palette rule (same as the web): body = traits[0] % 8, pattern = traits[2] % 3 (0 plain, 1 belly, 2 spots).",
  "// Entries 1..4 = outline, body, shade, light; 5..13 fixed; 14 = belly, 15 = spot (see nl_build_palette).",
  `static const uint16_t NL_BODY_PALETTES[${BODY_PALETTES.length}][4] = {`,
  ...BODY_PALETTES.map((p) => `  { ${p.colours.map((c) => hex16(rgb565(c))).join(", ")} },  // ${p.name}`),
  "};",
);
const normal = buildPalette([0, 0, 0, 0, 0], "normal");
const grey = buildPalette([0, 0, 0, 0, 0], "grey");
lines.push(
  `static const uint16_t NL_FIXED_PALETTE[16] = { ${normal.rgb.map((c, i) => (i >= 5 && i <= 13 ? hex16(rgb565(c)) : "0x0000")).join(", ")} };`,
  `static const uint16_t NL_GREY_PALETTE[16] = { ${grey.rgb.map((c, i) => (i === 14 || i === 15 ? "0x0000" : hex16(rgb565(c)))).join(", ")} };`,
  "",
  "// Fills out[16] (RGB565; swap bytes if your display driver expects it).",
  "static inline void nl_build_palette(const uint8_t traits[5], bool grey, uint16_t out[16]) {",
  `  const uint16_t* body = NL_BODY_PALETTES[traits[0] % ${BODY_PALETTES.length}];`,
  "  uint8_t pattern = traits[2] % 3;",
  "  for (int i = 0; i < 16; i++) out[i] = grey ? NL_GREY_PALETTE[i] : NL_FIXED_PALETTE[i];",
  "  if (!grey) { out[1] = body[0]; out[2] = body[1]; out[3] = body[2]; out[4] = body[3]; }",
  "  out[14] = pattern == 1 ? out[4] : out[2];",
  "  out[15] = pattern == 2 ? out[3] : out[2];",
  "}",
  "",
  "typedef struct {",
  "  const char* name;       // e.g. \"idle\", \"pat\", \"egg_hatch\"",
  "  uint8_t stage;          // 0 egg, 1 baby, 2 teen, 3 adult (same as the contract's stage)",
  "  uint8_t winged;         // 1 = winged form",
  "  uint8_t fps;",
  "  uint8_t loop;           // 0 = one-shot, then return to the state loop",
  "  uint8_t grey;           // 1 = use the grey palette (starving, dormant)",
  "  uint8_t frame_count;",
  "  const uint8_t* frames;  // frame_count * NL_FRAME_BYTES",
  "} nl_clip_t;",
  "",
);

const STAGE_NUM: Record<Stage, number> = { egg: 0, baby: 1, teen: 2, adult: 3 };
for (const set of SETS) {
  for (const anim of set.anims) {
    const c = clip(anim, { stage: set.stage, winged: set.winged });
    const id = `NL_${ident(set.stage)}${set.winged ? "_W" : ""}_${ident(anim)}`;
    const bytes = c.frames.flatMap((f) => Array.from(pack4(f)));
    totalFrames += c.frames.length;
    lines.push(`static const uint8_t ${id}[${bytes.length}] = {`);
    for (let i = 0; i < bytes.length; i += 32) {
      lines.push("  " + bytes.slice(i, i + 32).map((v) => `0x${v.toString(16).padStart(2, "0")}`).join(",") + ",");
    }
    lines.push("};");
    table.push(`  { "${anim}", ${STAGE_NUM[set.stage]}, ${set.winged ? 1 : 0}, ${c.fps}, ${c.loop ? 1 : 0}, ${c.palette === "grey" ? 1 : 0}, ${c.frames.length}, ${id} },`);
    meta.push({ anim, stage: set.stage, winged: set.winged, fps: c.fps, loop: c.loop, grey: c.palette === "grey", frames: c.frames.length });
  }
}

lines.push("", `static const nl_clip_t NL_CLIPS[${table.length}] = {`, ...table, "};", `#define NL_CLIP_COUNT ${table.length}`, "");
lines.push(
  "// Find a clip; returns nullptr if missing.",
  "static inline const nl_clip_t* nl_find_clip(const char* name, uint8_t stage, uint8_t winged) {",
  "  for (int i = 0; i < NL_CLIP_COUNT; i++) {",
  "    const nl_clip_t* c = &NL_CLIPS[i];",
  "    if (c->stage != stage || c->winged != (stage == 0 ? 0 : winged)) continue;",
  "    const char* a = c->name; const char* b = name;",
  "    while (*a && *a == *b) { a++; b++; }",
  "    if (*a == *b) return c;",
  "  }",
  "  return nullptr;",
  "}",
  "",
);

writeFileSync(join(ART, "nearling_sprites.h"), lines.join("\n"));
writeFileSync(join(ART, "sprites.json"), JSON.stringify({ size: SIZE, bitsPerPixel: 4, clips: meta }, null, 2) + "\n");

// Review sheets: one per stage/form with a sample palette.
for (const set of SETS) {
  const clips = set.anims.map((a) => clip(a, { stage: set.stage, winged: set.winged }));
  const S = 4;
  const CELL = SIZE * S + 8;
  const cols = Math.max(...clips.map((c) => c.frames.length));
  const W = cols * CELL;
  const H = clips.length * CELL;
  const img = new Uint8Array(W * H * 4);
  for (let i = 0; i < W * H; i++) img.set([12, 10, 8, 255], i * 4);
  clips.forEach((c, row) => {
    const pal = paletteFor([2, 0, 1, 0, 0], c);
    c.frames.forEach((f, col) => {
      const rgba = toRgba(f, pal);
      for (let y = 0; y < SIZE; y++) for (let x = 0; x < SIZE; x++) {
        const s = (y * SIZE + x) * 4;
        if (rgba[s + 3] === 0) continue;
        for (let sy = 0; sy < S; sy++) for (let sx = 0; sx < S; sx++) {
          img.set([rgba[s]!, rgba[s + 1]!, rgba[s + 2]!, 255], ((row * CELL + 4 + y * S + sy) * W + col * CELL + 4 + x * S + sx) * 4);
        }
      }
    });
  });
  writeFileSync(join(ART, "sheets", `${set.stage}${set.winged ? "-winged" : ""}.png`), encodePng(W, H, img));
}

console.log(`art/: ${table.length} clips, ${totalFrames} frames, ${(totalFrames * 512 / 1024).toFixed(0)} KB of frame data`);
