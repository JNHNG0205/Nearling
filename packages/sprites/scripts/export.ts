// Generates the firmware and art files from the same frames the web renders.
//   art/nearling_sprites.h   C header for the ESP32 (4 bpp frame pool in flash, RGB565 palettes, clip table)
//   art/sprites.json         clip metadata (names, fps, loop, frame counts) for any other tool
//   art/sheets/*.png         review sheets
// Usage: pnpm --filter @nearling/sprites export   (then `check-header` to compile and compare)
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  BODY_PALETTES, EGG_ANIMS, PERSONALITIES, PERSONALITY_ANIMS, PET_ANIMS, SHIRT_COLOURS, SIZE, clip, pack4,
  type AnyAnim, type Clip, type PetAnim, type Personality, type Stage,
} from "../src/index";
import { buildPalette, type Rgb } from "../src/palette";
import { PERSONALITY_MIN } from "../src/personality";
import { renderSheet } from "./sheet-lib";

const ART = join(dirname(fileURLToPath(import.meta.url)), "../../../art");
mkdirSync(join(ART, "sheets"), { recursive: true });

const rgb565 = ([r, g, b]: Rgb) => ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3);
const hex16 = (v: number) => `0x${v.toString(16).padStart(4, "0")}`;
const ident = (s: string) => s.toUpperCase().replace(/[^A-Z0-9]/g, "_");

/** Every clip the device carries, in table order (check-header.ts uses the same list). */
export interface ExportClip {
  anim: AnyAnim;
  stage: Stage;
  winged: boolean;
  personality: Personality | null;
  clip: Clip;
}

export function exportClips(): ExportClip[] {
  const out: ExportClip[] = [];
  for (const anim of Object.keys(EGG_ANIMS) as AnyAnim[]) {
    out.push({ anim, stage: "egg", winged: false, personality: null, clip: clip(anim, { stage: "egg", winged: false }) });
  }
  for (const stage of ["baby", "teen", "adult"] as const) {
    for (const winged of [false, true]) {
      for (const anim of Object.keys(PET_ANIMS) as PetAnim[]) {
        out.push({ anim, stage, winged, personality: null, clip: clip(anim, { stage, winged, shirt: "0" }) });
        for (const personality of PERSONALITIES) {
          if (!PERSONALITY_ANIMS[personality][anim]) continue;
          out.push({ anim, stage, winged, personality, clip: clip(anim, { stage, winged, shirt: "0", personality }) });
        }
      }
    }
  }
  return out;
}

const STAGE_NUM: Record<Stage, number> = { egg: 0, baby: 1, teen: 2, adult: 3 };
export const personalityNum = (p: Personality | null) => (p ? PERSONALITIES.indexOf(p) + 1 : 0);

function main() {
  const clips = exportClips();

  // Frame pool: identical 4 bpp frames (base or shirt layer) are stored once.
  const pool: number[][] = [];
  const poolIndex = new Map<string, number>();
  const intern = (f: Uint8Array) => {
    const packed = Array.from(pack4(f));
    const k = Buffer.from(packed).toString("base64");
    let id = poolIndex.get(k);
    if (id === undefined) {
      id = pool.length;
      pool.push(packed);
      poolIndex.set(k, id);
    }
    return id;
  };

  const lines: string[] = [];
  const lists: string[] = [];
  const table: string[] = [];
  const meta: Record<string, unknown>[] = [];
  let frameRefs = 0;

  for (const c of clips) {
    const id = `NL_${ident(c.stage)}${c.winged ? "_W" : ""}_${ident(c.anim)}${c.personality ? `_${ident(c.personality)}` : ""}`;
    const frames = c.clip.frames.map(intern);
    lists.push(`static const uint16_t ${id}_F[${frames.length}] = { ${frames.join(", ")} };`);
    let shirtRef = "nullptr";
    if (c.clip.shirt) {
      lists.push(`static const uint16_t ${id}_S[${frames.length}] = { ${c.clip.shirt.map(intern).join(", ")} };`);
      shirtRef = `${id}_S`;
    }
    frameRefs += frames.length * (c.clip.shirt ? 2 : 1);
    table.push(
      `  { "${c.anim}", ${STAGE_NUM[c.stage]}, ${c.winged ? 1 : 0}, ${personalityNum(c.personality)}, ${c.clip.fps}, ${c.clip.loop ? 1 : 0}, ${c.clip.palette === "grey" ? 1 : 0}, ${frames.length}, ${id}_F, ${shirtRef} },`,
    );
    meta.push({
      anim: c.anim, stage: c.stage, winged: c.winged, personality: c.personality, fps: c.clip.fps, loop: c.clip.loop,
      grey: c.clip.palette === "grey", frames: frames.length, shirt: c.clip.shirt !== null,
    });
  }

  const normal = buildPalette([0, 0, 0, 0, 0], "normal");
  const grey = buildPalette([0, 0, 0, 0, 0], "grey");
  const greyShirts = SHIRT_COLOURS.map((_, i) => buildPalette([0, 0, 0, 0, 0], "grey", String(i)).shirt!);

  lines.push(
    "// GENERATED by packages/sprites/scripts/export.ts. Do not edit; change the poses and re-run.",
    "// Spec: web-app architectual/07-pet-animation.md (section 6: device draw order).",
    "#pragma once",
    "#include <stdint.h>",
    "",
    `#define NL_SPRITE_SIZE ${SIZE}`,
    `#define NL_FRAME_BYTES ${(SIZE * SIZE) / 2}  // 4 bits per pixel, high nibble = left pixel, index 0 = transparent`,
    "",
    "// Palette rule (same as the web): body = traits[0] % 8, pattern = traits[2] % 3 (0 plain, 1 belly, 2 spots).",
    "// Entries 1..4 = outline, body, shade, light; 5..13 fixed; 14 = belly, 15 = spot (see nl_build_palette).",
    `static const uint16_t NL_BODY_PALETTES[${BODY_PALETTES.length}][4] = {`,
    ...BODY_PALETTES.map((p) => `  { ${p.colours.map((c) => hex16(rgb565(c))).join(", ")} },  // ${p.name}`),
    "};",
    `static const uint16_t NL_FIXED_PALETTE[16] = { ${normal.rgb.map((c, i) => (i >= 5 && i <= 13 ? hex16(rgb565(c)) : "0x0000")).join(", ")} };`,
    `static const uint16_t NL_GREY_PALETTE[16] = { ${grey.rgb.map((c, i) => (i === 14 || i === 15 ? "0x0000" : hex16(rgb565(c)))).join(", ")} };`,
    "",
    "// Fills out[16] (RGB565; swap bytes if your display driver expects it).",
    "static inline void nl_build_palette(const uint8_t traits[5], bool grey, uint16_t out[16]) {",
    `  const uint16_t* body = NL_BODY_PALETTES[traits[0] % ${BODY_PALETTES.length}];`,
    "  uint8_t pattern = traits[2] % 3;",
    "  for (int i = 0; i < 16; i++) out[i] = grey ? NL_GREY_PALETTE[i] : NL_FIXED_PALETTE[i];",
    "  if (!grey) { out[1] = body[0]; out[2] = body[1]; out[3] = body[2]; out[4] = body[3]; }",
    "  out[14] = pattern == 1 ? out[4] : out[2];",
    "  out[15] = pattern == 2 ? out[3] : out[2];",
    "}",
    "",
    "// Closet shirt (Build Spec 5): a second 4 bpp layer per frame, 1 = cloth, 2 = shade, 3 = trim, 0 = transparent.",
    "// Colour from the equipped token id: h = h * 31 + char (uint32) over the id string, colour = h % 8.",
    `static const uint16_t NL_SHIRT_PALETTES[${SHIRT_COLOURS.length}][3] = {`,
    ...SHIRT_COLOURS.map((s) => `  { ${s.colours.map((c) => hex16(rgb565(c))).join(", ")} },  // ${s.name}`),
    "};",
    `static const uint16_t NL_SHIRT_GREY_PALETTES[${SHIRT_COLOURS.length}][3] = {`,
    ...greyShirts.map((s, i) => `  { ${s.slice(1).map((c) => hex16(rgb565(c))).join(", ")} },  // ${SHIRT_COLOURS[i]!.name}`),
    "};",
    "static inline uint8_t nl_shirt_colour(const char* token_id) {",
    "  uint32_t h = 0;",
    "  while (*token_id) h = h * 31u + (uint8_t)*token_id++;",
    `  return (uint8_t)(h % ${SHIRT_COLOURS.length}u);`,
    "}",
    "// Fills out[4] for the shirt layer (out[0] unused). Grey clips use the grey shirt.",
    "static inline void nl_build_shirt_palette(const char* token_id, bool grey, uint16_t out[4]) {",
    "  const uint16_t* s = grey ? NL_SHIRT_GREY_PALETTES[nl_shirt_colour(token_id)] : NL_SHIRT_PALETTES[nl_shirt_colour(token_id)];",
    "  out[0] = 0; out[1] = s[0]; out[2] = s[1]; out[3] = s[2];",
    "}",
    "",
    `// Personality (CLAUDE.md 5.4 order): highest trait wins if >= ${PERSONALITY_MIN}, ties to the lower index.`,
    `// 0 none, ${PERSONALITIES.map((p, i) => `${i + 1} ${p}`).join(", ")}.`,
    "static inline uint8_t nl_personality(const uint8_t traits[5]) {",
    "  uint8_t best = 0;",
    "  for (uint8_t i = 1; i < 5; i++) if (traits[i] > traits[best]) best = i;",
    `  return traits[best] >= ${PERSONALITY_MIN} ? (uint8_t)(best + 1) : 0;`,
    "}",
    "",
    "typedef struct {",
    "  const char* name;       // e.g. \"idle\", \"pat\", \"egg_hatch\"",
    "  uint8_t stage;          // 0 egg, 1 baby, 2 teen, 3 adult (same as the contract's stage)",
    "  uint8_t winged;         // 1 = winged form",
    "  uint8_t personality;    // 0 = default clip, else nl_personality() value this variant is for",
    "  uint8_t fps;",
    "  uint8_t loop;           // 0 = one-shot, then return to the state loop",
    "  uint8_t grey;           // 1 = use the grey palette (starving, dormant)",
    "  uint8_t frame_count;",
    "  const uint16_t* frames; // frame_count ids into NL_FRAME_DATA (nl_frame)",
    "  const uint16_t* shirt;  // frame_count shirt layer ids, or nullptr (egg)",
    "} nl_clip_t;",
    "",
    `#define NL_FRAME_COUNT ${pool.length}`,
    `static const uint8_t NL_FRAME_DATA[NL_FRAME_COUNT * NL_FRAME_BYTES] = {`,
  );
  for (const f of pool) {
    for (let i = 0; i < f.length; i += 32) {
      lines.push("  " + f.slice(i, i + 32).map((v) => `0x${v.toString(16).padStart(2, "0")}`).join(",") + ",");
    }
  }
  lines.push(
    "};",
    "static inline const uint8_t* nl_frame(uint16_t id) { return NL_FRAME_DATA + (uint32_t)id * NL_FRAME_BYTES; }",
    "",
    ...lists,
    "",
    `static const nl_clip_t NL_CLIPS[${table.length}] = {`,
    ...table,
    "};",
    `#define NL_CLIP_COUNT ${table.length}`,
    "",
    "// Find a clip: the personality variant if one exists, else the default clip; nullptr if missing.",
    "static inline const nl_clip_t* nl_find_clip(const char* name, uint8_t stage, uint8_t winged, uint8_t personality = 0) {",
    "  const nl_clip_t* fallback = nullptr;",
    "  for (int i = 0; i < NL_CLIP_COUNT; i++) {",
    "    const nl_clip_t* c = &NL_CLIPS[i];",
    "    if (c->stage != stage || c->winged != (stage == 0 ? 0 : winged)) continue;",
    "    if (c->personality != 0 && c->personality != personality) continue;",
    "    const char* a = c->name; const char* b = name;",
    "    while (*a && *a == *b) { a++; b++; }",
    "    if (*a != *b) continue;",
    "    if (c->personality == personality) return c;",
    "    fallback = c;",
    "  }",
    "  return fallback;",
    "}",
    "",
  );

  writeFileSync(join(ART, "nearling_sprites.h"), lines.join("\n"));
  writeFileSync(join(ART, "sprites.json"), JSON.stringify({ size: SIZE, bitsPerPixel: 4, clips: meta }, null, 2) + "\n");

  // Review sheets: one per stage/form with a sample palette (no shirt, no personality), then the shirt and personality sheets.
  for (const stage of ["egg", "baby", "teen", "adult"] as const) {
    for (const winged of stage === "egg" ? [false] : [false, true]) {
      const names = (stage === "egg" ? Object.keys(EGG_ANIMS) : Object.keys(PET_ANIMS)) as AnyAnim[];
      writeFileSync(
        join(ART, "sheets", `${stage}${winged ? "-winged" : ""}.png`),
        renderSheet(names.map((n) => ({ clip: clip(n, { stage, winged }), traits: [2, 0, 1, 0, 0], shirt: null }))),
      );
    }
  }
  // shirts: each colour (token ids "0".."7") on each stage and form, idle frame 0 and talk frame 1
  const shirtRows = (["baby", "teen", "adult"] as const).flatMap((stage) => [false, true].map((winged) => ({ stage, winged })));
  writeFileSync(
    join(ART, "sheets", "shirts.png"),
    renderSheet(
      shirtRows.flatMap(({ stage, winged }) =>
        ["idle", "talk", "starving"].map((a) => ({ clip: clip(a as PetAnim, { stage, winged, shirt: "0" }), traits: [1, 0, 1, 0, 0], shirt: "0" })),
      ),
      { columns: SHIRT_COLOURS.map((_, i) => ({ frame: 0, shirt: String(i) })) },
    ),
  );
  // personality: default clip, then the variant, for every animation that has one (adult, winged, red shirt)
  const pRows = PERSONALITIES.flatMap((p) =>
    (Object.keys(PERSONALITY_ANIMS[p]) as PetAnim[]).flatMap((a) => [
      { clip: clip(a, { stage: "adult", winged: true, shirt: "0" }), traits: [5, 0, 0, 0, 0], shirt: "0" },
      { clip: clip(a, { stage: "adult", winged: true, shirt: "0", personality: p }), traits: [5, 0, 0, 0, 0], shirt: "0" },
    ]),
  );
  writeFileSync(join(ART, "sheets", "personality.png"), renderSheet(pRows));

  const kb = (pool.length * 512) / 1024;
  console.log(
    `art/: ${table.length} clips, ${frameRefs} frame refs, ${pool.length} unique 4 bpp frames = ${kb.toFixed(0)} KB frame data`,
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
